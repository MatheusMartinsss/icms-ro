// Nomes do IBGE que a SEFAZ escreve de outro jeito.
const ALIAS: Record<string, string> = {
  'NOSSA SENHORA DO LIVRAMENTO': 'NOSSA SRA DO LIVRAMENTO',
  POXOREO: 'POXOREU',
  'SANTO ANTONIO DO LEVERGER': 'SANTO ANTONIO DE LEVERGER',
}

// Mesma normalização do gdare: maiúsculas, sem acento, apóstrofo vira espaço.
export function normalizarMunicipio(nome: string) {
  const n = nome.normalize('NFD').replace(/\p{M}/gu, '').toUpperCase()
    .replace(/['`´]/g, ' ').replace(/\s+/g, ' ').trim()
  return ALIAS[n] ?? n
}

const CONHECIDOS = new Set(MUNICIPIOS_MT.map(normalizarMunicipio))

export const municipioMtValido = (nome: string) => CONHECIDOS.has(normalizarMunicipio(nome))
